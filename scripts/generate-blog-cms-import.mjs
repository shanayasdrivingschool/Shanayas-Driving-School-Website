import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { JSDOM } from "jsdom";
import { loadSiteContent } from "./load-site-content.mjs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const outputPath = path.resolve(__dirname, "../supabase/migrations/20261008030000_current_blog_import.sql");

const sqlString = (value) => `'${String(value ?? "").replaceAll("'", "''")}'`;
const sqlJson = (value) => `${sqlString(JSON.stringify(value))}::jsonb`;

const content = await loadSiteContent();
const rows = [];

for (const [slug, post] of content.blogPosts) {
  const document = new JSDOM(`<body>${post.html}</body>`).window.document;
  const text = document.body.textContent?.replace(/\s+/g, " ").trim() ?? "";
  const contentBlocks = [{
    id: `imported-${slug}`,
    type: "rich_html",
    text,
    html: post.html,
  }];
  const faqs = (post.faqs ?? []).map((faq, index) => ({ id: `imported-${slug}-faq-${index + 1}`, ...faq }));
  const author = content.resolveAuthor(post.authorId);
  const reviewer = content.resolveAuthor(post.reviewedById);
  const authorName = author?.name ?? post.author ?? "Shanaya's Driving School";
  const reviewerName = reviewer?.name ?? "";
  const canonicalPath = post.canonicalPath ?? `/blog/${slug}/`;
  const seoTitle = post.seoTitle ?? post.title;
  const snapshot = {
    slug,
    title: post.title,
    category: post.category,
    excerpt: post.description,
    contentBlocks,
    coverImageUrl: post.heroImage ?? "",
    coverImageAlt: post.title,
    seoTitle,
    metaDescription: post.description,
    canonicalPath,
    ogTitle: seoTitle,
    ogDescription: post.description,
    ogImageUrl: post.heroImage ?? "",
    robots: "index, follow",
    schemaType: "BlogPosting",
    breadcrumbSchemaEnabled: true,
    faqSchemaEnabled: faqs.length > 0,
    faqs,
    relatedSlugs: post.relatedSlugs ?? [],
    authorName,
    reviewerName,
    datePublished: post.datePublished,
    dateModified: post.dateModified,
    sourceOrigin: "code_import",
  };

  rows.push(`(
    ${sqlString(slug)},
    ${sqlString(post.title)},
    'published',
    'awaiting_evidence_review',
    'implemented_locally',
    ${sqlString(post.category)},
    ${sqlString(post.description)},
    ${sqlJson(contentBlocks)},
    ${sqlString(post.heroImage ?? "")},
    ${sqlString(post.title)},
    ${sqlString(seoTitle)},
    ${sqlString(post.description)},
    ${sqlString(canonicalPath)},
    ${sqlString(seoTitle)},
    ${sqlString(post.description)},
    ${sqlString(post.heroImage ?? "")},
    'index, follow',
    'BlogPosting',
    true,
    ${faqs.length > 0},
    ${sqlJson(faqs)},
    ${sqlJson(post.relatedSlugs ?? [])},
    ${sqlJson([])},
    ${sqlJson({
      primaryReader: "",
      targetQuestion: "",
      location: "Victoria, British Columbia",
      intendedOutcome: "",
      scope: "Imported from the current code-authored article.",
      overlap: "Existing public article with the same stable slug.",
      evidenceGaps: "Recheck time-sensitive claims and record the evidence used for the proposed revision.",
      originalContribution: "",
      responsibleAuthor: authorName,
      nextStep: "",
      maintenanceDate: "",
    })},
    ${sqlString(authorName)},
    ${sqlString(reviewerName)},
    '',
    ${Boolean(reviewerName)},
    null,
    ${sqlString(post.datePublished)}::timestamptz,
    'code_import',
    ${sqlJson(snapshot)},
    ${sqlString(post.dateModified)}::timestamptz
  )`);
}

const migration = `-- Generated by scripts/generate-blog-cms-import.mjs.
-- Imports the current code-authored articles without replacing any existing CMS row.
begin;

alter table public.blog_posts
  add column if not exists source_origin text not null default 'cms'
    check (source_origin in ('cms', 'code_import')),
  add column if not exists published_snapshot jsonb,
  add column if not exists published_revision_at timestamptz;

create or replace function public.protect_published_blog_identity()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if old.published_snapshot is not null and new.slug is distinct from old.slug then
    raise exception 'The slug of an existing published article is locked. Create a redirect plan before changing its URL.';
  end if;
  return new;
end;
$$;

drop trigger if exists trg_protect_published_blog_identity on public.blog_posts;
create trigger trg_protect_published_blog_identity
before update on public.blog_posts
for each row execute function public.protect_published_blog_identity();

drop policy if exists "Blog editors can delete blog posts" on public.blog_posts;
create policy "Blog editors can delete unpublished blog posts"
on public.blog_posts for delete to authenticated
using (
  ((select public.is_admin_user()) or (select public.is_seo_user()))
  and published_snapshot is null
);

insert into public.blog_posts (
  slug, title, status, readiness, publication_state, category, excerpt, content_blocks,
  cover_image_url, cover_image_alt, seo_title, meta_description, canonical_path,
  og_title, og_description, og_image_url, robots, schema_type,
  breadcrumb_schema_enabled, faq_schema_enabled, faqs, related_slugs, annotations,
  editorial_brief, author_name, reviewer_name, review_scope, review_required,
  reviewed_at, published_at, source_origin, published_snapshot, published_revision_at
)
values
${rows.join(",\n")}
on conflict (slug) do nothing;

commit;
`;

await fs.writeFile(outputPath, migration, "utf8");
console.log(`Wrote ${rows.length} current articles to ${path.relative(process.cwd(), outputPath)}`);
